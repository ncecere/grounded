#!/usr/bin/env python3
"""Deterministic bounded projection of canonical Kustomize (ADR-0031)."""
import argparse
import hashlib
import itertools
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile

import yaml

ROOT = Path(__file__).resolve().parents[3]
K8S = ROOT / 'deploy/kubernetes'
CHART = ROOT / 'deploy/helm/grounded'
COMPONENTS = ('postgres-single', 'valkey-single', 'ocr-tesseract', 'ingress',
              'tracing', 'monitoring-annotations')
FLAGS = ('(eq .Values.postgres "bundled")', '(eq .Values.valkey "bundled")',
         '.Values.ocr', '.Values.ingress', '.Values.tracing', '.Values.monitoring')
HEADER = '# Code generated by deploy/helm/scripts/generate.py; DO NOT EDIT.\n'


def run(*args):
    return subprocess.check_output(args, text=True, timeout=60)


def render(bits):
    with tempfile.TemporaryDirectory(prefix='.helm-', dir=K8S) as tmp:
        k = {'apiVersion': 'kustomize.config.k8s.io/v1beta1', 'kind': 'Kustomization',
             'resources': ['../base'],
             'components': ['../components/' + c for c, b in zip(COMPONENTS, bits) if b]}
        Path(tmp, 'kustomization.yaml').write_text(yaml.safe_dump(k))
        return list(yaml.safe_load_all(run(os.getenv('KUSTOMIZE', 'kustomize'), 'build', tmp)))


def condition(states):
    # Merge adjacent boolean cubes; a don't-care eliminates irrelevant components.
    cubes = set(states)
    while True:
        merged, used = set(), set()
        for a in cubes:
            for b in cubes:
                diff = [i for i in range(6) if a[i] != b[i]]
                if len(diff) == 1 and a[diff[0]] != -1 and b[diff[0]] != -1:
                    c = list(a)
                    c[diff[0]] = -1
                    merged.add(tuple(c))
                    used.update((a, b))
        new = (cubes - used) | merged
        if new == cubes:
            break
        cubes = new
    clauses = []
    for cube in sorted(cubes):
        terms = [f if b else '(not ' + f + ')' for b, f in zip(cube, FLAGS) if b != -1]
        if not terms:
            return 'true'
        clauses.append(terms[0] if len(terms) == 1 else '(and ' + ' '.join(terms) + ')')
    return clauses[0] if len(clauses) == 1 else '(or ' + ' '.join(clauses) + ')'


def expression(key):
    return '{{ .Values.' + key + ' | toJson }}'


def project(obj):
    """Only the following leaves are values; everything else is canonical."""
    tokens = {}

    def value(parent, key, name):
        token = 'HELMVALUE' + str(len(tokens))
        parent[key] = token
        tokens[token] = expression(name)

    meta = obj['metadata']
    meta['namespace'] = 'HELMNAMESPACE'
    tokens['HELMNAMESPACE'] = '{{ .Release.Namespace | toJson }}'
    kind, name = obj['kind'], meta['name']
    if kind == 'ConfigMap':
        for key, field in [('APP_URL', 'appURL'), ('S3_ENDPOINT', 's3Endpoint'),
                           ('S3_BUCKET', 's3Bucket'),
                           ('OTEL_EXPORTER_OTLP_ENDPOINT', 'tracingEndpoint'),
                           ('OTEL_TRACES_SAMPLER_ARG', 'tracingSample')]:
            if key in obj['data']:
                value(obj['data'], key, field)
    if kind == 'Deployment':
        component = name.removeprefix('grounded-')
        value(obj['spec'], 'replicas', component + 'Replicas')
    if kind in ('Deployment', 'StatefulSet'):
        pod = obj['spec']['template']['spec']
        for c in pod.get('initContainers', []) + pod['containers']:
            if c['image'].startswith('ghcr.io/ncecere/grounded-ocr:'):
                value(c, 'image', 'ocrImage')
            elif c['image'].startswith('ghcr.io/ncecere/grounded:'):
                value(c, 'image', 'appImage')
    if kind == 'Ingress':
        value(obj['spec']['rules'][0], 'host', 'ingressHost')
        value(obj['spec'], 'ingressClassName', 'ingressClass')
        obj['spec']['tls'] = [{'hosts': ['HELMHOST'], 'secretName': 'HELMTLS'}]
        tokens['HELMHOST'] = expression('ingressHost')
        tokens['HELMTLS'] = expression('tlsSecret')
    if kind == 'NetworkPolicy':
        spec = obj['spec']
        if name == 'grounded-api-ingress':
            value(spec['ingress'][0]['from'][0]['namespaceSelector']['matchLabels'],
                  'kubernetes.io/metadata.name', 'ingressNamespace')
        if name in ('grounded-app-egress-tracing', 'grounded-allow-metrics-scrape'):
            rule = spec['egress'][0]['to'][0] if 'egress' in spec else spec['ingress'][0]['from'][0]
            value(rule['namespaceSelector']['matchLabels'], 'kubernetes.io/metadata.name',
                  'tracingNamespace' if 'tracing' in name else 'monitoringNamespace')
    text = yaml.safe_dump(obj, sort_keys=True, width=1000)
    for old, new in tokens.items():
        text = text.replace(old, new)
    for old, field in [('grounded-runtime', 'runtimeSecret'), ('grounded-s3', 's3Secret'),
                       ('grounded-smtp', 'smtpSecret')]:
        text = text.replace('name: ' + old + '\n', 'name: ' + expression(field) + '\n')
    return text


def generate():
    groups = {}
    configs = {}
    for bits in itertools.product((0, 1), repeat=6):
        for obj in render(bits):
            if obj['kind'] == 'Secret':
                raise ValueError('canonical input contains a Secret; chart must never emit credentials')
            # ConfigMap hash is recomputed by Helm from the selected data template.
            raw = json.dumps(obj)
            raw = re.sub(r'grounded-config-[a-z0-9]{10}', 'grounded-config-HELMHASH', raw)
            obj = json.loads(raw)
            text = project(obj)
            target = configs if obj['kind'] == 'ConfigMap' else groups
            target.setdefault(text, set()).add(bits)
    files = {'templates/validate.yaml': HEADER + (ROOT / 'deploy/helm/inputs/validate.tpl').read_text()}
    config = ''
    for text, bits in sorted(configs.items()):
        data = text[text.index('data:\n') + 6:text.index('kind: ConfigMap')]
        config += '{{ if ' + condition(bits) + ' }}\n' + data + '{{ end }}\n'
    files['templates/_config.tpl'] = HEADER + '{{ define "grounded.data" }}\n' + config + '{{ end }}\n'
    bodies = []
    for text, bits in sorted(groups.items()):
        text = text.replace('HELMHASH', '{{ include "grounded.data" . | sha256sum | trunc 10 }}')
        bodies.append('{{ if ' + condition(bits) + ' }}\n---\n' + text + '{{ end }}\n')
    # The ConfigMap metadata is generated from the canonical rendered object, too.
    sample = next(iter(configs))
    metadata = ('apiVersion: v1\n' + sample[sample.index('kind: ConfigMap'):]).replace(
        'HELMHASH', '{{ include "grounded.data" . | sha256sum | trunc 10 }}')
    files['templates/objects.yaml'] = HEADER + ''.join(bodies) + '---\n' + metadata + 'data:\n{{ include "grounded.data" . }}\n'
    sources = [p for p in (K8S / 'base').rglob('*') if p.is_file()]
    for component in COMPONENTS:
        sources += [p for p in (K8S / 'components' / component).rglob('*') if p.is_file()]
    sources += list(Path(__file__).parent.glob('*.py'))
    sources += list(Path(__file__).parent.glob('*.sh'))
    sources += [CHART / n for n in ('Chart.yaml', 'values.yaml', 'values.schema.json')]
    sources += list((ROOT / 'deploy/helm/inputs').glob('*'))
    files['provenance.json'] = json.dumps({
        'kustomize': 'v5.8.1', 'helm': 'v3.17.3',
        'sources': {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest()
                    for p in sorted(sources)}}, indent=2) + '\n'
    return files


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    files = generate()
    # Only generator-owned files; chart metadata/schema are maintained inputs.
    actual = {str(p.relative_to(CHART)) for p in (CHART / 'templates').glob('*')}
    actual.add('provenance.json')
    if args.check:
        stale = actual ^ set(files)
        stale |= {n for n, content in files.items()
                  if not (CHART / n).exists() or (CHART / n).read_text() != content}
        if stale:
            raise SystemExit('stale generated chart: ' + ', '.join(sorted(stale)))
        print('generated chart unchanged')
    else:
        for n in actual - set(files):
            (CHART / n).unlink(missing_ok=True)
        for n, content in files.items():
            p = CHART / n
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(content)


if __name__ == '__main__':
    main()
